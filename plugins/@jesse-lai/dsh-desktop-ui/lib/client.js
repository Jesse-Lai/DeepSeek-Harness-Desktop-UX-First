    function syncFixedComposerLayout() {
      composerLayoutAnimationFrame = undefined;
      captureHeroComposerLayout();
      const seat = document.querySelector(
        '[data-phase="active"] > [data-conversation-scroll] > [data-composer-seat]',
      );
      const scrollport = seat?.parentElement;
      if (
        !(seat instanceof HTMLElement) ||
        !(scrollport instanceof HTMLElement) ||
        !scrollport.matches("[data-conversation-scroll]")
      ) {
        composerLayoutResizeObserver?.disconnect();
        composerLayoutObservedSeat = undefined;
        composerLayoutObservedScrollport = undefined;
        clearFixedComposerLayout();
        markScrollButton();
        return;
      }

      document.querySelectorAll("[data-dsh-composer-fixed]").forEach((marked) => {
        if (marked === seat || !(marked instanceof HTMLElement)) return;
        marked.style.removeProperty("--dsh-desktop-composer-bottom");
        marked.style.removeProperty("--dsh-desktop-composer-left");
        marked.style.removeProperty("--dsh-desktop-composer-seat-width");
        resetComposerEntryStyles(marked);
        delete marked.dataset.dshComposerFixed;
      });
      document.querySelectorAll("[data-dsh-composer-fixed-host]").forEach((marked) => {
        if (marked === scrollport || !(marked instanceof HTMLElement)) return;
        marked.style.removeProperty("--dsh-desktop-composer-reserve");
        delete marked.dataset.dshComposerFixedHost;
      });

      const layoutTargetChanged =
        composerLayoutObservedSeat !== seat ||
        composerLayoutObservedScrollport !== scrollport;
      if (layoutTargetChanged && composerEntrySeat !== seat) {
        clearComposerEntryAnimation();
      }
      if (layoutTargetChanged) composerLayoutLastGeometry = "";
      if (layoutTargetChanged && typeof ResizeObserver === "function") {
        composerLayoutResizeObserver?.disconnect();
        composerLayoutResizeObserver = new ResizeObserver(scheduleFixedComposerLayout);
        composerLayoutResizeObserver.observe(seat);
        composerLayoutResizeObserver.observe(scrollport);
        composerLayoutObservedSeat = seat;
        composerLayoutObservedScrollport = scrollport;
      }

      const scrollRect = scrollport.getBoundingClientRect();
      const card = seat.querySelector("[data-composer-card]");
      const todoPanel = prepareTodoOverlay(seat);
      const seatHeight = seat.offsetHeight || seat.getBoundingClientRect().height;
      const viewportHeight = Number.isFinite(window.innerHeight)
        ? window.innerHeight
        : document.documentElement.clientHeight;
      const left = scrollRect.left + (scrollport.clientLeft || 0);
      const bottom = Math.max(0, viewportHeight - scrollRect.bottom);
      const width = scrollport.clientWidth || scrollRect.width;
      const geometry = [left, bottom, width, seatHeight]
        .map((value) => Math.round(value * 100) / 100);
      if (!geometry.every(Number.isFinite)) return;

      const wasAtBottom =
        scrollport.scrollHeight - scrollport.clientHeight - scrollport.scrollTop <= 25;
      seat.dataset.dshComposerFixed = "";
      scrollport.dataset.dshComposerFixedHost = "";
      const serialized = geometry.join(":");
      if (serialized !== composerLayoutLastGeometry) {
        composerLayoutLastGeometry = serialized;
        seat.style.setProperty("--dsh-desktop-composer-left", `${geometry[0]}px`);
        seat.style.setProperty("--dsh-desktop-composer-bottom", `${geometry[1]}px`);
        seat.style.setProperty("--dsh-desktop-composer-seat-width", `${geometry[2]}px`);
        scrollport.style.setProperty("--dsh-desktop-composer-reserve", `${geometry[3]}px`);
        if (wasAtBottom) scrollport.scrollTop = scrollport.scrollHeight;
      }
      positionTodoOverlay(todoPanel, card, seat);
      animateFixedComposerFromHero(seat);
      markScrollButton();
    }

    function scheduleFixedComposerLayout() {
      if (composerLayoutAnimationFrame !== undefined) return;
      composerLayoutAnimationFrame = window.requestAnimationFrame(syncFixedComposerLayout);
    }

    function positionScrollButton(button, card) {
      if (!(button instanceof HTMLElement) || !(card instanceof HTMLElement)) return;
      const cardRect = card.getBoundingClientRect();
      const todoPanel = card
        .closest("[data-composer-seat]")
        ?.querySelector('[data-testid="todo-panel"][data-dsh-todo-overlay]');
      const todoRect = todoPanel?.getBoundingClientRect();
      const left = cardRect.left + cardRect.width / 2 - 18;
      const anchorTop =
        todoRect !== undefined && todoRect.height > 0
          ? Math.min(cardRect.top, todoRect.top)
          : cardRect.top;
      const top = anchorTop - 36 - 12;
      if (!Number.isFinite(left) || !Number.isFinite(top)) return;
      button.style.setProperty(
        "--dsh-desktop-scroll-left",
        `${Math.round(left * 100) / 100}px`,
      );
      button.style.setProperty(
        "--dsh-desktop-scroll-top",
        `${Math.round(top * 100) / 100}px`,
      );
    }

    function findScrollButton(card) {
      if (!(card instanceof HTMLElement)) return null;
      const scrollport = card.closest("[data-conversation-scroll]");
      if (!(scrollport instanceof HTMLElement)) return null;

      for (const flow of scrollport.querySelectorAll("[data-chat-flow]")) {
        const list = flow.parentElement;
        if (!(list instanceof HTMLElement)) continue;
        for (const slot of list.children) {
          if (!(slot instanceof HTMLElement) || slot === flow) continue;
          const button = slot.matches("button")
            ? slot
            : slot.querySelector(":scope > button");
          if (
            button instanceof HTMLElement &&
            button.querySelector(
              'svg[data-lucide-animated-icon="chevron-down"]',
            ) !== null
          ) {
            return button;
          }
        }
      }
      return null;
    }

