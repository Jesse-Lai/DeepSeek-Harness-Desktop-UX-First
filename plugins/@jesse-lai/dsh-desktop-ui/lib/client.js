    const steerStoragePrefix = "dsh-steer-cuts:v1:";

    function currentSteerSession(ctx) {
      try {
        const sessionId = ctx.sessions?.list?.getSnapshot?.().current;
        if (sessionId === undefined || sessionId === null || sessionId === "") return null;
        const session = ctx.sessions?.binding?.(sessionId)?.session;
        return session === undefined ? null : { session, sessionId: String(sessionId) };
      } catch {
        return null;
      }
    }

    function emptySteerRecord() {
      return { discardedKeys: [], internalKeys: [] };
    }

    function readSteerRecord(sessionId) {
      if (typeof localStorage === "undefined") return emptySteerRecord();
      try {
        const value = JSON.parse(localStorage.getItem(`${steerStoragePrefix}${sessionId}`) || "null");
        return {
          discardedKeys: Array.isArray(value?.discardedKeys)
            ? value.discardedKeys.filter((key) => typeof key === "string")
            : [],
          internalKeys: Array.isArray(value?.internalKeys)
            ? value.internalKeys.filter((key) => typeof key === "string")
            : [],
        };
      } catch {
        return emptySteerRecord();
      }
    }

    function writeSteerRecord(sessionId, record) {
      if (typeof localStorage === "undefined") return;
      try {
        localStorage.setItem(`${steerStoragePrefix}${sessionId}`, JSON.stringify({
          discardedKeys: [...new Set(record.discardedKeys)],
          internalKeys: [...new Set(record.internalKeys)],
        }));
      } catch {
        /* A storage failure should not prevent the in-memory steering action. */
      }
    }

    function steerRowKey(row) {
      return row.dataset.chatAnchorKey || "";
    }

    function closeSteerEditor(state) {
      const editor = state.openEditor;
      if (!(editor instanceof HTMLElement)) return;
      const row = editor.closest("[data-chat-flow-kind]");
      editor.remove();
      if (row instanceof HTMLElement) delete row.dataset.dshSteerOpen;
      state.openEditor = null;
    }

