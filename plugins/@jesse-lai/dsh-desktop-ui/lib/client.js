    function markComposer(card) {
      if (!(card instanceof HTMLElement)) return;
      const input = card.querySelector(":scope > [data-input-scroll]");
      if (!(input instanceof HTMLElement)) return;

      input.dataset.dshComposerInput = "";
      const textarea = input.querySelector("textarea");
      if (textarea instanceof HTMLElement && textarea.dataset.dshComposerOriginalPlaceholder === undefined) {
        textarea.dataset.dshComposerOriginalPlaceholder = textarea.getAttribute("placeholder") ?? "";
        textarea.setAttribute("placeholder", "Do Anything");
      }
      for (const child of card.children) {
        if (child !== input && child !== input.nextElementSibling && child instanceof HTMLElement) {
          child.dataset.dshComposerFullWidth = "";
        }
      }

      const row = input.nextElementSibling;
      if (!(row instanceof HTMLElement)) return;
      row.dataset.dshComposerRow = "";

      const tools = row.firstElementChild;
      const trailing = row.lastElementChild;
      if (tools instanceof HTMLElement) {
        tools.dataset.dshComposerTools = "";
        const toolItems = Array.from(tools.children).filter((item) => item instanceof HTMLElement);
        if (toolItems[0]) toolItems[0].dataset.dshComposerCommand = "";
        if (toolItems[1]) {
          toolItems[1].dataset.dshComposerModes = "";
          const permissionTrigger = toolItems[1].querySelector("button");
          if (permissionTrigger instanceof HTMLElement) {
            permissionTrigger.dataset.dshComposerMenuTrigger = "permission";
          }
        }
        for (const item of toolItems.slice(2)) item.dataset.dshComposerExtra = "";
      }
      if (trailing instanceof HTMLElement) {
        trailing.dataset.dshComposerTrailing = "";
        const buttons = trailing.querySelectorAll("button");
        const modelTrigger = [...buttons].find(
          (button) => button.getAttribute("aria-haspopup") === "menu",
        );
        if (modelTrigger instanceof HTMLElement) {
          modelTrigger.dataset.dshComposerMenuTrigger = "model";
        }
        const primary = buttons[buttons.length - 1];
        if (primary instanceof HTMLElement) primary.dataset.dshComposerPrimary = "";
        for (const button of buttons) {
          if (button.querySelector('svg rect[x="3"][y="3"][width="10"][height="10"]')) {
            button.dataset.dshComposerPrimary = "";
          }
        }
      }
    }

