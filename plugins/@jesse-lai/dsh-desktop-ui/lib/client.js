      const textNode = liveStatusTextNode(status);
      if (status.dataset.dshLiveStatusAddedText !== undefined) textNode?.remove();
      else if (textNode !== undefined && status.dataset.dshLiveStatusOriginal !== undefined) {
        textNode.nodeValue = status.dataset.dshLiveStatusOriginal;
      }
      status.style.removeProperty("display");
