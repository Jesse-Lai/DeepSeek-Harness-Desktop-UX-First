    function syncFeedbackDialogDecoration(shell, decoration, editor, textarea, opener) {
      if (decoration.editor !== editor) {
        delete decoration.editor.dataset.dshFeedbackSource;
        decoration.editor = editor;
      }
      decoration.textarea = textarea;
      decoration.opener = opener;
      editor.dataset.dshFeedbackSource = "";

      const copy = feedbackDialogCopy();
      decoration.dialog.setAttribute("aria-label", copy.label);
      decoration.title.textContent = copy.title;
      decoration.input.setAttribute("aria-label", copy.inputLabel);
      decoration.input.setAttribute("placeholder", copy.placeholder);
      decoration.cancel.textContent = copy.cancel;
      decoration.save.textContent = copy.save;
      if (document.activeElement !== decoration.input) {
        decoration.input.value = textarea.value ?? "";
      }

      const sourceSave = editor.querySelector('button[class*="_noteSave"]');
      decoration.save.disabled =
        !(sourceSave instanceof HTMLElement) || sourceSave.disabled === true;

      const currentStatuses = new Set(
        Array.from(shell.querySelectorAll('[role="status"]')).filter(
          (candidate) => candidate instanceof HTMLElement,
        ),
      );
      for (const sourceStatus of decoration.sourceStatuses) {
        if (!currentStatuses.has(sourceStatus)) {
          delete sourceStatus.dataset.dshFeedbackSourceStatus;
        }
      }
      for (const sourceStatus of currentStatuses) {
        sourceStatus.dataset.dshFeedbackSourceStatus = "";
      }
      decoration.sourceStatuses = currentStatuses;
      decoration.status.textContent = Array.from(currentStatuses)
        .map((sourceStatus) => String(sourceStatus.textContent ?? "").trim())
        .filter(Boolean)
        .join(" ");
    }

