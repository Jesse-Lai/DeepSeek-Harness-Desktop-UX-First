    function commandMenuIconSlug(button) {
      const label = button.querySelector('[class*="_itemName"]');
      const commandName = label?.textContent
        ?.trim()
        .toLowerCase()
        .replace(/^\/+/, "")
        .split(/\s+/, 1)[0];
      if (commandName && commandMenuIconSlugs[commandName] !== undefined) {
        return commandMenuIconSlugs[commandName];
      }

      const source = button.id.match(/^dsh-slash-option-(.+)-\d+$/)?.[1];
      if (source === "skill") return "file-cog";
      if (source === "subagent") return "bot";
      return "terminal";
    }

