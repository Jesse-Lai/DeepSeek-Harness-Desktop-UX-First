    function syncFeedbackDialogs(dialogs, pendingRequests) {
      for (const [button] of pendingRequests) {
        if (!button.isConnected) clearPendingFeedbackRequest(button, pendingRequests);
      }

      for (const button of document.querySelectorAll(
        "button[data-dsh-feedback-dialog-pending]",
      )) {
        if (!isFeedbackDislikeButton(button)) {
          clearPendingFeedbackRequest(button, pendingRequests);
          continue;
        }
        if (button.getAttribute("aria-pressed") !== "true") continue;
        const row = feedbackActionRow(button);
        const note = row?.querySelector('button[class*="_noteOpen"]');
        if (!(note instanceof HTMLElement)) continue;
        clearPendingFeedbackRequest(button, pendingRequests);
        note.click();
        window.requestAnimationFrame(() => {
          syncFeedbackDialogs(dialogs, pendingRequests);
        });
      }

      const activeShells = new Set();
      for (const editor of document.querySelectorAll('span[class*="_noteEditor"]')) {
        if (!(editor instanceof HTMLElement)) continue;
        const shell = editor.parentElement;
        const textarea = editor.querySelector("textarea");
        if (!(shell instanceof HTMLElement) || !(textarea instanceof HTMLElement)) continue;
        activeShells.add(shell);

        let decoration = dialogs.get(shell);
        if (decoration === undefined) {
          const opener = Array.from(
            shell.querySelectorAll('button[aria-pressed="true"]'),
          ).find(isFeedbackDislikeButton);
          if (!(opener instanceof HTMLElement)) {
            closeFeedbackDialog(shell);
            continue;
          }

          decoration = createFeedbackPortal(shell, editor, textarea, opener);
          dialogs.set(shell, decoration);
          syncFeedbackDialogDecoration(shell, decoration, editor, textarea, opener);
          window.requestAnimationFrame(() => {
            if (decoration.input.isConnected) {
              decoration.input.focus({ preventScroll: true });
            }
          });
        } else {
          const opener = Array.from(
            shell.querySelectorAll('button[aria-pressed="true"]'),
          ).find(isFeedbackDislikeButton);
          if (!(opener instanceof HTMLElement)) {
            closeFeedbackDialog(shell);
            continue;
          }
          if (decoration.portal.parentElement !== document.body) {
            document.body.append(decoration.portal);
          }
          syncFeedbackDialogDecoration(shell, decoration, editor, textarea, opener);
        }
      }

      for (const [shell, decoration] of dialogs) {
        if (activeShells.has(shell) && shell.isConnected) continue;
        removeFeedbackDialog(shell, decoration, true);
        dialogs.delete(shell);
      }
      if (dialogs.size === 0) delete document.body.dataset.dshFeedbackModalOpen;
      else document.body.dataset.dshFeedbackModalOpen = "";
    }

    function handleFeedbackDialogKeydown(event, dialogs) {
      const [shell, decoration] = dialogs.entries().next().value ?? [];
      if (!(shell instanceof HTMLElement) || !shell.isConnected) return;
      if (event.key === "Escape" && !event.isComposing) {
        event.preventDefault();
        event.stopPropagation();
        closeFeedbackDialog(shell);
        return;
      }
      if (event.key !== "Tab") return;

      const controls = Array.from(
        decoration.dialog.querySelectorAll("textarea, button:not([disabled])"),
      ).filter((control) => control instanceof HTMLElement);
      if (controls.length === 0) return;
      const first = controls[0];
      const last = controls.at(-1);
      const active = document.activeElement;
      if (!controls.includes(active)) {
        event.preventDefault();
        first.focus({ preventScroll: true });
        return;
      }
      if (event.shiftKey ? active !== first : active !== last) return;
      event.preventDefault();
      (event.shiftKey ? last : first).focus({ preventScroll: true });
    }

