    function trimGoal(goal, maximum = 72) {
      const normalized = String(goal)
        .replace(/\s+/g, " ")
        .replace(/[。！？.!?;；]+$/g, "")
        .trim();
      if (normalized.length <= maximum) return normalized;
      return `${normalized.slice(0, maximum).trimEnd()}…`;
    }

    /** Extract the next concrete objective from ordinary-language progress prose. */
    function goalFromProgressText(copy, language = "en") {
      const text = String(copy).trim();
      if (text === "") return "";
      if (language === "zh") {
        const sentences = text.split(/[。！？\n]+/).map((sentence) => sentence.trim()).filter(Boolean);
        for (const sentence of [...sentences].reverse()) {
          const marker = sentence.match(/(?:接下来|下一步|随后|然后|现在)[，,:：\s]?(.*)$/);
          const future = sentence.match(/(?:我|我们)(?:会|将|要|先|准备|打算)(.*)$/);
          if (marker === null && future === null) continue;
          let goal = marker?.[1] ?? future?.[1] ?? "";
          goal = goal
            .replace(/^(?:我|我们)\s*/, "")
            .replace(/^(?:(?:会|将|要|先|准备|打算)\s*)+/, "")
            .split(/[，,]\s*(?:然后|再|随后|接着|之后)/, 1)[0];
          goal = trimGoal(goal);
          if (goal !== "") return goal;
        }
        return "";
      }

      const sentences = text.split(/[.!?\n]+/).map((sentence) => sentence.trim()).filter(Boolean);
      for (const sentence of [...sentences].reverse()) {
        const patterns = [
          /\bnext\s*[:,]?\s*(.*)$/i,
          /\b(?:I|we)(?:'ll| will| am going to| are going to| plan to)\s+(.*)$/i,
        ];
        const match = patterns.map((pattern) => sentence.match(pattern)).find(Boolean);
        if (match === undefined) continue;
        const goal = trimGoal((match[1] ?? "")
          .replace(/^(?:I|we)(?:'ll| will| am going to| are going to| plan to)\s+/i, "")
          .split(/,?\s+(?:and then|then)\s+/i, 1)[0]);
        if (goal !== "") return goal;
      }
      return "";
    }

    /** The todo row summary is "counts · active objective". */
    function goalFromTodoSummary(summary) {
      const parts = String(summary)
        .split(/\s*[·•]\s*/)
        .map((part) => trimGoal(part))
        .filter(Boolean);
      if (parts.length < 2) return "";
      return parts.slice(1).find((part) => !/^\+?\d+(?:\s|$)/.test(part)) ?? "";
    }

    function operationDetail(running) {
      const header = running.querySelector("[data-disclosure-row]");
      if (!(header instanceof HTMLElement)) return "";
      const detail = Array.from(header.children)
        .slice(2)
        .map((child) => (child.textContent || "").replace(/\s+/g, " ").trim())
        .filter(Boolean)
        .join(" · ");
      if (detail !== "") return detail;
      return (header.textContent || "").replace(/\s+/g, " ").trim();
    }

    function latestTodoGoal(rows) {
      for (const row of [...rows].reverse()) {
        const todo = rowTools(row).filter((tool) => tool.dataset.tool === "todo_write").at(-1);
        if (!(todo instanceof HTMLElement)) continue;
        const goal = goalFromTodoSummary(operationDetail(todo));
        if (goal !== "") return goal;
      }
      return "";
    }

    function latestProgressGoal(rows, language) {
      for (const row of [...rows].reverse()) {
        if (row.dataset.chatFlowKind !== "assistant-step") continue;
        const copy = assistantBlocks(row)
          .filter((block) => block.dataset.variant !== "think")
          .map((block) => block.textContent || "")
          .filter(Boolean)
          .join("\n");
        const goal = goalFromProgressText(copy, language);
        if (goal !== "") return goal;
      }
      return "";
    }

    function latestRunningOperation(rows) {
      for (const row of [...rows].reverse()) {
        if (row.dataset.dshImmediate !== undefined || row.dataset.dshTodoHistory !== undefined) continue;
        const running = Array.from(row.querySelectorAll('[data-state="running"]'))
          .filter((candidate) => candidate instanceof HTMLElement)
          .at(-1);
        if (!(running instanceof HTMLElement)) continue;
        const tool = running.dataset.tool !== undefined
          ? running
          : running.querySelector("[data-tool]");
        const toolName = tool instanceof HTMLElement
          ? tool.dataset.tool || "tool"
          : row.dataset.chatFlowKind === "command" ? "command" : "tool";
        return {
          family: toolFamily(toolName),
          detail: operationDetail(running),
        };
      }
      return null;
    }

