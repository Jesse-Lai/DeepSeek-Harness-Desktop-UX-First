    function anchorSequence(session, anchorKey) {
      try {
        const node = session.getSnapshot?.().chat?.nodes?.get?.(anchorKey);
        return node?.data?.finalNode?.seq ?? node?.anchorSeq ?? null;
      } catch {
        return null;
      }
    }

    function steeringPrompt({ anchorCopy, anchorKey, anchorSeq, comment }) {
      const location = anchorSeq === null
        ? `conversation node ${anchorKey}`
        : `conversation node ${anchorKey} (sequence ${anchorSeq})`;
      return [
        "Internal steering instruction: continue the user's existing task from the retained checkpoint below.",
        `User correction: ${comment}`,
        `Retained checkpoint (${location}): ${anchorCopy}`,
        "Everything produced after that checkpoint on the previous path is discarded and invalid, including assistant reasoning, plans, messages, tool results, and conclusions.",
        "Do not rely on the discarded path. Re-read or re-derive any facts you still need from the retained checkpoint and the user's correction.",
        "Files or other residual state may have been created or changed by the discarded path. Treat that residual state as untrusted: ignore it unless you independently revalidate it against the retained checkpoint and the user's correction.",
        "Continue naturally without repeating this internal instruction or describing the discarded path.",
      ].join("\n\n");
    }

    function applyStoredSteerCuts(ctx, state) {
      const current = currentSteerSession(ctx);
      if (current === null) return;
      const record = readSteerRecord(current.sessionId);
      const discarded = new Set(record.discardedKeys);
      const internal = new Set(record.internalKeys);
      for (const flow of document.querySelectorAll("[data-chat-flow]")) {
        if (!(flow instanceof HTMLElement)) continue;
        const rows = flowRows(flow);
        for (const row of rows) {
          const key = steerRowKey(row);
          if (discarded.has(key)) row.dataset.dshSteerDiscarded = "";
          if (internal.has(key)) row.dataset.dshSteerInternal = "";
        }

        const pending = state.pending;
        if (pending === null || pending.sessionId !== current.sessionId) continue;
        const newRows = rows.filter((row) => {
          const key = steerRowKey(row);
          return key !== "" && !pending.knownKeys.has(key) && !discarded.has(key);
        });
        if (pending.internalKey === "") {
          const internalRow = newRows.find((row) => row.dataset.chatFlowKind === "user");
          const key = internalRow === undefined ? "" : steerRowKey(internalRow);
          if (internalRow !== undefined && key !== "") {
            internalRow.dataset.dshSteerInternal = "";
            pending.internalKey = key;
            record.internalKeys.push(key);
            writeSteerRecord(current.sessionId, record);
          }
        }
        const continuation = newRows.find((row) => {
          const kind = row.dataset.chatFlowKind;
          return kind !== "user" && row.dataset.dshSteerDiscarded === undefined;
        });
        if (continuation !== undefined) {
          clearSteerStatus(state);
          state.pending = null;
        }
      }
    }

    function syncSteerActions(ctx, state) {
      applyStoredSteerCuts(ctx, state);
      const triggerCopy = progressLanguage() === "zh"
        ? "从此处重新思考"
        : "Steer from here";
      for (const flow of document.querySelectorAll("[data-chat-flow]")) {
        if (!(flow instanceof HTMLElement)) continue;
        const rows = flowRows(flow);
        let latestQueryIndex = -1;
        for (let index = 0; index < rows.length; index += 1) {
          if (
            rows[index].dataset.chatFlowKind === "user" &&
            rows[index].dataset.dshSteerDiscarded === undefined
          ) latestQueryIndex = index;
        }
        for (let index = 0; index < rows.length; index += 1) {
          const row = rows[index];
          const eligible = latestQueryIndex >= 0 &&
            index > latestQueryIndex &&
            row.dataset.dshProgressUpdate !== undefined &&
            row.dataset.dshSteerDiscarded === undefined &&
            row.querySelector("[data-streaming]") === null;
          const existing = row.querySelector("[data-dsh-steer-action]");
          if (!eligible) {
            if (existing === state.openEditor?.parentElement) closeSteerEditor(state);
            existing?.remove();
            continue;
          }
          if (existing instanceof HTMLElement) {
            const trigger = existing.querySelector("[data-dsh-steer-trigger]");
            if (trigger instanceof HTMLElement) trigger.textContent = triggerCopy;
            continue;
          }
          const action = document.createElement("div");
          action.dataset.dshSteerAction = "";
          const trigger = document.createElement("button");
          trigger.type = "button";
          trigger.dataset.dshSteerTrigger = "";
          trigger.textContent = triggerCopy;
          action.append(trigger);
          row.append(action);
        }
      }
    }

    async function submitSteer(row, editor, ctx, state) {
      if (state.submitting) return;
      const input = editor.querySelector("[data-dsh-steer-input]");
      const comment = input instanceof HTMLElement ? input.value.trim() : "";
      if (comment === "") return;
      const current = currentSteerSession(ctx);
      if (current === null) return;
      const flow = row.parentElement;
      if (!(flow instanceof HTMLElement)) return;

      state.submitting = true;
      const submit = editor.querySelector("[data-dsh-steer-submit]");
      if (submit instanceof HTMLElement) submit.disabled = true;
      const previous = readSteerRecord(current.sessionId);
      const record = {
        discardedKeys: [...previous.discardedKeys],
        internalKeys: [...previous.internalKeys],
      };
      const rows = flowRows(flow);
      const anchorIndex = rows.indexOf(row);
      const suffix = anchorIndex < 0 ? [] : rows.slice(anchorIndex + 1);
      const newlyDiscarded = [];
      for (const suffixRow of suffix) {
        suffixRow.dataset.dshSteerDiscarded = "";
        newlyDiscarded.push(suffixRow);
        const key = steerRowKey(suffixRow);
        if (key !== "") record.discardedKeys.push(key);
      }
      writeSteerRecord(current.sessionId, record);
      closeSteerEditor(state);
      appendSteerStatus(row, state);
      state.pending = {
        internalKey: "",
        knownKeys: new Set(rows.map(steerRowKey).filter(Boolean)),
        sessionId: current.sessionId,
      };

      try {
        const anchorKey = steerRowKey(row);
        const prompt = steeringPrompt({
          anchorCopy: assistantSteerCopy(row),
          anchorKey,
          anchorSeq: anchorSequence(current.session, anchorKey),
          comment,
        });
        const running = current.session.getSnapshot?.().running === true;
        const result = await current.session.prompt(
          [{ type: "text", text: prompt }],
          running ? "steer" : "queue",
        );
        if (result?.ok !== true) throw new Error("Steer prompt was not accepted");
      } catch {
        writeSteerRecord(current.sessionId, previous);
        for (const suffixRow of newlyDiscarded) {
          const key = steerRowKey(suffixRow);
          if (!previous.discardedKeys.includes(key)) delete suffixRow.dataset.dshSteerDiscarded;
        }
        clearSteerStatus(state);
        state.pending = null;
      } finally {
        state.submitting = false;
      }
    }

    function handleSteerClick(event, ctx, state) {
      const target = event.target;
      if (!(target instanceof HTMLElement)) {
        closeSteerEditor(state);
        return;
      }
      const submit = target.closest("[data-dsh-steer-submit]");
      if (submit instanceof HTMLElement) {
        event.preventDefault();
        event.stopPropagation();
        const editor = submit.closest("[data-dsh-steer-editor]");
        const row = submit.closest("[data-chat-flow-kind]");
        if (editor instanceof HTMLElement && row instanceof HTMLElement) {
          void submitSteer(row, editor, ctx, state);
        }
        return;
      }
      const trigger = target.closest("[data-dsh-steer-trigger]");
      if (trigger instanceof HTMLElement) {
        event.preventDefault();
        event.stopPropagation();
        const row = trigger.closest("[data-chat-flow-kind]");
        if (row instanceof HTMLElement) openSteerEditor(row, state);
        return;
      }
      if (target.closest("[data-dsh-steer-editor]") === null) closeSteerEditor(state);
    }

    function handleSteerInput(event) {
      const editor = event.target instanceof HTMLElement
        ? event.target.closest("[data-dsh-steer-editor]")
        : null;
      if (editor instanceof HTMLElement) updateSteerSubmit(editor);
    }

    function handleSteerKeydown(event, ctx, state) {
      if (event.key === "Escape" && !event.isComposing && state.openEditor !== null) {
        event.preventDefault();
        event.stopPropagation();
        closeSteerEditor(state);
        return;
      }
      if (event.key !== "Enter" || event.shiftKey || event.isComposing) return;
      const editor = event.target instanceof HTMLElement
        ? event.target.closest("[data-dsh-steer-editor]")
        : null;
      const row = editor?.closest("[data-chat-flow-kind]");
      if (editor instanceof HTMLElement && row instanceof HTMLElement) {
        event.preventDefault();
        event.stopPropagation();
        void submitSteer(row, editor, ctx, state);
      }
    }

