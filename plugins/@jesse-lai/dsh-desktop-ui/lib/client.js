    function markLiveTurnStatus(flow, rows, language) {
      const current = [...rows].reverse().find((row) => row.dataset.chatFlowKind === "user");
      const currentIndex = current === undefined ? -1 : rows.indexOf(current);
      const currentRows = rows.slice(currentIndex + 1);
      const hasVisibleProgress = currentRows.some((row) =>
        row.dataset.dshProgressUpdate !== undefined ||
        row.dataset.dshActivityGroup !== undefined ||
        row.dataset.dshRetry !== undefined ||
        row.dataset.dshFinalAnswer !== undefined ||
        row.dataset.chatFlowKind === "tool-call" ||
        row.dataset.chatFlowKind === "command" ||
        (row.dataset.chatFlowKind === "assistant-step" && assistantHasUserCopy(row)));
      const status = Array.from(flow.children).find((child) =>
        child instanceof HTMLElement &&
        child.dataset.chatFlowKind === undefined &&
        child.getAttribute("role") === "status");
      if (!(status instanceof HTMLElement)) return;

      status.dataset.dshLiveStatus = "";
      const waitingForUser = currentRows.some((row) =>
        row.dataset.dshImmediate !== undefined && rowHasRunningTool(row));
      if (waitingForUser || flow.querySelector('[data-approval-key]') !== null) {
        status.style.setProperty("display", "none", "important");
        status.dataset.dshLiveStatusSource = "waiting";
        return;
      }

      status.style.removeProperty("display");
      const operation = latestRunningOperation(currentRows);
      if (operation !== null) {
        status.dataset.dshLiveStatusSource = "operation";
        setLiveStatusCopy(status, liveStatusCopy({ stage: "operation", ...operation }, language));
        return;
      }
      const retrying = currentRows.some((row) => row.dataset.dshRetryActive !== undefined);
      if (retrying) {
        status.dataset.dshLiveStatusSource = "retry";
        setLiveStatusCopy(status, liveStatusCopy({ stage: "retry" }, language));
        return;
      }
      const goal = latestTodoGoal(currentRows) || latestProgressGoal(currentRows, language);
      if (goal !== "") {
        status.dataset.dshLiveStatusSource = "goal";
        setLiveStatusCopy(status, liveStatusCopy({ stage: "goal", detail: goal }, language));
        return;
      }
      const stage = hasVisibleProgress ? "working" : "initial";
      status.dataset.dshLiveStatusSource = stage;
      setLiveStatusCopy(status, liveStatusCopy({ stage }, language));
    }

