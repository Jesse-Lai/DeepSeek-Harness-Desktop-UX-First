    function hashIconGeometry(value) {
      let hash = 2166136261;
      for (let index = 0; index < value.length; index += 1) {
        hash ^= value.charCodeAt(index);
        hash = Math.imul(hash, 16777619);
      }
      return hash >>> 0;
    }

    function iconGeometryHash(svg) {
      const rows = [];
      const elements = svg.querySelectorAll(
        "circle, ellipse, g, line, path, polygon, polyline, rect",
      );
      for (const element of elements) {
        /* Decorations are appended inside the React-owned SVG. Exclude that
           generated subtree so a later React geometry change (for example,
           Send arrow -> Stop square) can be detected from the source icon. */
        if (
          element.dataset?.lucideLibraryPaint !== undefined ||
          element.closest?.("[data-lucide-library-paint]") !== null
        ) continue;
        const row = [element.localName];
        for (const attribute of iconGeometryAttributes) {
          if (element.hasAttribute(attribute)) {
            row.push(`${attribute}=${element.getAttribute(attribute)}`);
          }
        }
        rows.push(row.join("|"));
      }
      return hashIconGeometry(rows.join(";"));
    }

    function createLibraryIcon(slug) {
      const markup = animatedIconMarkup[slug];
      if (markup === undefined) return null;
      const template = document.createElement("template");
      template.innerHTML = markup;
      const icon = template.content.firstElementChild;
      if (typeof SVGElement === "undefined" || !(icon instanceof SVGElement)) return null;
      icon.dataset.lucideLibraryPaint = "";
      icon.setAttribute("x", "0");
      icon.setAttribute("y", "0");
      icon.setAttribute("width", "100%");
      icon.setAttribute("height", "100%");
      icon.setAttribute("pointer-events", "none");
      return icon;
    }

    function createInjectedLibraryIcon(slug, kind) {
      const libraryIcon = createLibraryIcon(slug);
      if (libraryIcon === null) return null;
      const icon = document.createElementNS("http://www.w3.org/2000/svg", "svg");
      icon.setAttribute("viewBox", "0 0 24 24");
      icon.setAttribute("width", "14");
      icon.setAttribute("height", "14");
      icon.setAttribute("aria-hidden", "true");
      icon.setAttribute("focusable", "false");
      icon.dataset.lucideAnimatedIcon = slug;
      icon.dataset.dshLibraryIcon = kind;
      icon.append(libraryIcon);
      return icon;
    }

    function syncInjectedLibraryIcon(host, slug, kind, decorations) {
      let decoration = decorations.get(host);
      if (decoration !== undefined && decoration.icon.parentElement !== host) {
        decorations.delete(host);
        decoration = undefined;
      }
      if (decoration === undefined) {
        const icon = createInjectedLibraryIcon(slug, kind);
        if (icon === null) return null;
        host.append(icon);
        decoration = { icon, kind, slug };
        decorations.set(host, decoration);
      } else if (decoration.slug !== slug) {
        const libraryIcon = createLibraryIcon(slug);
        if (libraryIcon === null) return decoration;
        decoration.icon.replaceChildren(libraryIcon);
        decoration.icon.dataset.lucideAnimatedIcon = slug;
        decoration.slug = slug;
      }
      if (decoration.icon.dataset.dshLibraryIcon !== kind) {
        decoration.icon.dataset.dshLibraryIcon = kind;
      }
      decoration.kind = kind;
      if (host.dataset.dshLibraryIconHost !== kind) {
        host.dataset.dshLibraryIconHost = kind;
      }
      return decoration;
    }

