    function flowRows(flow) {
      return Array.from(flow.children).filter(
        (row) => row instanceof HTMLElement && row.dataset.chatFlowKind !== undefined,
      );
    }

    function rowTools(row) {
      return Array.from(row.querySelectorAll("[data-tool]"));
    }

    function rowToolNames(row) {
      return rowTools(row).map((tool) => tool.dataset.tool || "tool");
    }

    function isTodoRow(row) {
      const tools = rowTools(row);
      return tools.length > 0 && tools.every((tool) => tool.dataset.tool === "todo_write");
    }

    function isImmediateRow(row) {
      return rowTools(row).some((tool) => /^(ask_user_question|request_user_input|approval)$/i.test(tool.dataset.tool || ""));
    }

    function rowHasRunningTool(row) {
      return row.querySelector('[data-state="running"]') !== null;
    }

    function rowHasToolError(row) {
      return row.querySelector('[data-state="error"]') !== null;
    }

    function assistantHasUserCopy(row) {
      const root = row.firstElementChild;
      const body = root?.firstElementChild;
      if (!(body instanceof HTMLElement)) return false;
      return Array.from(body.children).some((block) => {
        if (!(block instanceof HTMLElement) || block.dataset.variant === "think") return false;
        return (block.textContent || "").trim() !== "" || block.querySelector("img") !== null;
      });
    }

    function nextRowsUntilUser(rows, index) {
      const result = [];
      for (let cursor = index + 1; cursor < rows.length; cursor += 1) {
        const candidate = rows[cursor];
        if (candidate.dataset.chatFlowKind === "user") break;
        result.push(candidate);
      }
      return result;
    }

    function resetProgressMarks(rows) {
      for (const row of rows) {
        if (row.dataset.dshActivityHead !== undefined && row.dataset.dshActivityGroup !== undefined) {
          if (row.getAttribute("aria-expanded") === "true") {
            expandedActivityGroups.add(row.dataset.dshActivityGroup);
          }
        }
        for (const key of progressMarkKeys) delete row.dataset[key];
        if (row.dataset.dshLegacyMilestone !== undefined) {
          delete row.dataset.milestoneId;
          delete row.dataset.dshLegacyMilestone;
        }
        if (row.dataset.dshActivityButton !== undefined) {
          row.removeAttribute("role");
          row.removeAttribute("tabindex");
          row.removeAttribute("aria-expanded");
          delete row.dataset.dshActivityButton;
        }
      }
    }

    function setLegacyMilestones(rows) {
      let milestoneId = "milestone:opening";
      for (const row of rows) {
        if (row.dataset.chatFlowKind === "user") {
          milestoneId = `milestone:${row.dataset.chatAnchorKey || "user"}`;
          continue;
        }
        if (row.dataset.milestoneId === undefined) {
          row.dataset.milestoneId = milestoneId;
          row.dataset.dshLegacyMilestone = "";
          row.dataset.dshMilestoneSource = "legacy";
        }
      }
    }

    function markReasoning(rows, language) {
      const pending = language === "zh" ? "正在理解需求…" : "Understanding the request…";
      const detail = language === "zh" ? "可展开查看推理详情" : "Expand for reasoning details";
      let hasRunningReasoning = false;
      for (const reasoning of document.querySelectorAll('[data-variant="think"]')) {
        if (!(reasoning instanceof HTMLElement)) continue;
        reasoning.dataset.dshDebugReasoning = "";
        const running = reasoning.dataset.state === "running";
        hasRunningReasoning ||= running;
        const summary = reasoning.querySelector('[data-follow-end]') ?? reasoning.querySelector('[class*="_summary"]');
        if (summary instanceof HTMLElement) {
          const copy = running ? pending : detail;
          if (summary.textContent !== copy) summary.textContent = copy;
        }
      }
      return hasRunningReasoning;
    }

    function markProgressAndFinal(rows, language) {
      for (let index = 0; index < rows.length; index += 1) {
        const row = rows[index];
        if (row.dataset.chatFlowKind !== "assistant-step" || !assistantHasUserCopy(row)) continue;
        const later = nextRowsUntilUser(rows, index);
        const laterAction = later.some((candidate) =>
          candidate.dataset.chatFlowKind === "tool-call" ||
          candidate.dataset.chatFlowKind === "command" ||
          candidate.dataset.chatFlowKind === "model-retry");
        if (laterAction) {
          row.dataset.dshProgressKind = "progress_update";
          row.dataset.dshProgressUpdate = "";
          row.dataset.dshProgressLabel = language === "zh" ? "进展" : "Progress";
        } else if (row.querySelector("[data-streaming]") === null) {
          row.dataset.dshProgressKind = "final";
          row.dataset.dshFinalAnswer = "";
        }
      }
    }

    function markSpecialRows(rows) {
      for (let index = 0; index < rows.length; index += 1) {
        const row = rows[index];
        const kind = row.dataset.chatFlowKind;
        if (kind === "context") row.dataset.dshContextHidden = "";
        if (isTodoRow(row)) row.dataset.dshTodoHistory = "";
        if (isImmediateRow(row)) {
          row.dataset.dshProgressKind = "question";
          row.dataset.dshImmediate = "";
        }
        if (kind === "model-retry") {
          row.dataset.dshProgressKind = "retry";
          row.dataset.dshRetry = "";
          if (row.querySelector("details[data-active]") !== null) row.dataset.dshRetryActive = "";
        }
        if (kind === "turn-error") {
          row.dataset.dshProgressKind = "blocker";
          row.dataset.dshBlocker = "";
        }
        if ((kind === "tool-call" || kind === "command") && rowHasToolError(row)) {
          const later = nextRowsUntilUser(rows, index);
          const recovered = later.some((candidate) =>
            candidate.querySelector('[data-state="ok"]') !== null ||
            candidate.dataset.dshProgressUpdate !== undefined ||
            candidate.dataset.dshFinalAnswer !== undefined);
          if (!recovered) {
            row.dataset.dshProgressKind = "blocker";
            row.dataset.dshBlocker = "";
          }
        }
      }
      document.querySelectorAll("[data-approval-key]").forEach((approval) => {
        if (!(approval instanceof HTMLElement)) return;
        approval.dataset.dshProgressKind = "approval";
        approval.dataset.dshImmediate = "";
      });
    }

    function applyActivityExpansion(group, expanded) {
      const head = group[0];
      if (!(head instanceof HTMLElement)) return;
      head.setAttribute("aria-expanded", String(expanded));
      syncActivityDisclosureIcon(head, expanded);
      for (let index = 0; index < group.length; index += 1) {
        const row = group[index];
        row.dataset.dshActivityExpanded = String(expanded);
        if (index > 0) row.dataset.dshActivityRow = "";
      }
      if (expanded) expandedActivityGroups.add(head.dataset.dshActivityGroup);
      else expandedActivityGroups.delete(head.dataset.dshActivityGroup);
    }

    function installActivityListener(head, rows) {
      let listener = progressRowListeners.get(head);
      if (listener === undefined) {
        const toggle = (event) => {
          if (event.type === "keydown" && event.key !== "Enter" && event.key !== " ") return;
          if (event.type === "click" && event.target !== head && head.getAttribute("aria-expanded") === "true") return;
          if (event.type === "keydown") event.preventDefault();
          const groupId = head.dataset.dshActivityGroup;
          if (groupId === undefined) return;
          const group = Array.from(document.querySelectorAll("[data-dsh-activity-group]"))
            .filter((row) => row instanceof HTMLElement && row.dataset.dshActivityGroup === groupId);
          applyActivityExpansion(group, head.getAttribute("aria-expanded") !== "true");
        };
        head.addEventListener("click", toggle);
        head.addEventListener("keydown", toggle);
        listener = () => {
          head.removeEventListener("click", toggle);
          head.removeEventListener("keydown", toggle);
        };
        progressRowListeners.set(head, listener);
      }
      head.dataset.dshActivityButton = "";
      head.setAttribute("role", "button");
      head.setAttribute("tabindex", "0");
      applyActivityExpansion(rows, expandedActivityGroups.has(head.dataset.dshActivityGroup));
    }

    function markActivityGroup(group, language) {
      const tools = group.flatMap((row) => {
        const names = rowToolNames(row).filter((name) => name !== "todo_write");
        return names.length > 0 ? names : ["command"];
      });
      const callCount = tools.length;
      if (group.length < 2 && callCount < 2 && !group.some(rowHasToolError)) return;
      const head = group[0];
      const groupId = `activity:${head.dataset.chatAnchorKey || head.dataset.milestoneId || "legacy"}`;
      const running = group.some(rowHasRunningTool);
      /* Unresolved errors were excluded as blockers. Recovered failures stay in
         the disclosure without turning the user-level summary into an alert. */
      const errors = 0;
      for (const row of group) {
        row.dataset.dshProgressKind = "activity_group";
        row.dataset.dshActivityGroup = groupId;
      }
      head.dataset.dshActivityHead = "";
      head.dataset.dshActivitySummary = summarizeActivity({ tools, running, errors }, language);
      installActivityListener(head, group);
    }

    function markActivityGroups(rows, language) {
      let group = [];
      const flush = () => {
        if (group.length > 0) markActivityGroup(group, language);
        group = [];
      };
      for (const row of rows) {
        const kind = row.dataset.chatFlowKind;
        const groupable = (kind === "tool-call" || kind === "command") &&
          row.dataset.dshTodoHistory === undefined &&
          row.dataset.dshImmediate === undefined &&
          row.dataset.dshBlocker === undefined;
        if (groupable) group.push(row);
        else flush();
      }
      flush();
    }

    function clearStaleActivityDisclosureIcons(rows) {
      for (const row of rows) {
        if (row.dataset.dshActivityHead !== undefined) continue;
        row.querySelector("[data-dsh-activity-disclosure]")?.remove();
      }
    }

    function markInitialThink(flow, rows, language, hasRunningReasoning) {
      const current = [...rows].reverse().find((row) => row.dataset.chatFlowKind === "user");
      const currentIndex = current === undefined ? -1 : rows.indexOf(current);
      const currentRows = rows.slice(currentIndex + 1);
      const hasSemanticStatus = currentRows.some((row) =>
        row.dataset.dshProgressUpdate !== undefined ||
        row.dataset.dshActivityGroup !== undefined ||
        row.dataset.dshRetry !== undefined ||
        row.dataset.dshBlocker !== undefined ||
        row.dataset.dshImmediate !== undefined ||
        row.dataset.dshFinalAnswer !== undefined);
      const status = Array.from(flow.children).find((child) =>
        child instanceof HTMLElement &&
        child.dataset.chatFlowKind === undefined &&
        child.getAttribute("role") === "status");
      if (!(status instanceof HTMLElement)) return;
      if (hasSemanticStatus || hasRunningReasoning) {
        status.style.setProperty("display", "none", "important");
        status.dataset.dshInitialThink = "hidden";
        return;
      }
      status.style.removeProperty("display");
      status.dataset.dshInitialThink = "";
      const copy = language === "zh" ? "Think · 正在理解需求…" : "Think · Understanding the request…";
      for (const child of status.childNodes) {
        if (child.nodeType === 3 && child.nodeValue?.trim() !== "") {
          if (child.nodeValue !== copy) child.nodeValue = copy;
          return;
        }
      }
      status.prepend(document.createTextNode(copy));
    }

    function markGeneratingProgress() {
      const language = progressLanguage();
      for (const flow of document.querySelectorAll("[data-chat-flow]")) {
        if (!(flow instanceof HTMLElement)) continue;
        const rows = flowRows(flow);
        resetProgressMarks(rows);
        setLegacyMilestones(rows);
        markProgressAndFinal(rows, language);
        markSpecialRows(rows);
        syncBlockerIcons(rows);
        markActivityGroups(rows, language);
        clearStaleActivityDisclosureIcons(rows);
        const hasRunningReasoning = markReasoning(rows, language);
        markInitialThink(flow, rows, language, hasRunningReasoning);
      }
    }

