    function findSidebarRoot(sidebarColumn) {
      if (!(sidebarColumn instanceof HTMLElement)) return null;
      const candidates = [sidebarColumn, ...sidebarColumn.querySelectorAll("div")];
      for (const candidate of candidates) {
        if (!(candidate instanceof HTMLElement)) continue;
        const [logo, newSession, region, foot, extra] = Array.from(candidate.children);
        if (extra !== undefined) continue;
        if (!(logo instanceof HTMLElement) || !(newSession instanceof HTMLElement)) continue;
        if (!(region instanceof HTMLElement) || !(foot instanceof HTMLElement)) continue;
        const newSessionButton = newSession.matches("button")
          ? newSession
          : newSession.querySelector("button");
        if (logo.querySelector("button") === null || !(newSessionButton instanceof HTMLElement)) continue;
        return candidate;
      }
      return null;
    }

    function markDesktopShell() {
      const overlay = document.querySelector("[data-shell-overlay]");
      const shell = overlay?.parentElement;
      if (!(shell instanceof HTMLElement)) return false;

      const sidebarColumn = shell.firstElementChild;
      const details = overlay.previousElementSibling;
      const center = details?.previousElementSibling;
      if (sidebarColumn instanceof HTMLElement) sidebarColumn.dataset.dshDesktopSidebarColumn = "";
      if (center instanceof HTMLElement) center.dataset.dshDesktopCenter = "";
      if (details instanceof HTMLElement) details.dataset.dshDesktopDetails = "";
      shell.dataset.dshDesktopShell = "";

      const sidebar = findSidebarRoot(sidebarColumn);
      if (sidebar === null) return true;
      sidebar.dataset.dshDesktopSidebar = "";

      const [logo, newSession, region, foot] = Array.from(sidebar.children);
      if (logo instanceof HTMLElement) logo.dataset.dshDesktopSidebarLogo = "";
      if (newSession instanceof HTMLElement) {
        const newSessionButton = newSession.matches("button")
          ? newSession
          : newSession.querySelector("button");
        if (newSessionButton instanceof HTMLElement) {
          newSessionButton.dataset.dshDesktopSidebarNew = "";
        }
      }
      if (region instanceof HTMLElement) {
        region.dataset.dshDesktopSidebarRegion = "";
      }
      if (foot instanceof HTMLElement) foot.dataset.dshDesktopSidebarFoot = "";
      return true;
    }

