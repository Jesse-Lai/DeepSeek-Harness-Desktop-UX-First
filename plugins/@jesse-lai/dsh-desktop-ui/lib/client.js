    function findSidebarRoot(sidebarColumn) {
      if (!(sidebarColumn instanceof HTMLElement)) return null;
      const candidates = [sidebarColumn, ...sidebarColumn.querySelectorAll("div")];
      for (const candidate of candidates) {
        if (!(candidate instanceof HTMLElement)) continue;
        const [logo, newSession, region, foot, extra] = Array.from(candidate.children);
        if (extra !== undefined) continue;
        if (!(logo instanceof HTMLElement) || !(newSession instanceof HTMLElement)) continue;
        if (!(region instanceof HTMLElement) || !(foot instanceof HTMLElement)) continue;
        const newSessionButton = newSession.matches("button")
          ? newSession
          : newSession.querySelector("button");
        if (logo.querySelector("button") === null || !(newSessionButton instanceof HTMLElement)) continue;
        return candidate;
      }
      return null;
    }

